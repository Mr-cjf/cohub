export const DEFAULT_ENV_CONTRACT = `执行器环境契约（通用原则 + 探测式自适应）

通用原则：
1. 自包含：你的每一条执行指令都应携带完成任务所需的全部信息（目标、路径/清单、约束、输出格式），不依赖父会话上下文。
2. 先验证再批量：对不确定的写法或 API，先跑最小探针验证通过，再批量执行；不要一次性把整批操作压进一个执行单元。
3. 工具批处理：一条消息里可以同时发出多个无依赖的工具调用，它们会作为一批进入执行器——所以「多个独立动作」应当打包成一批，而不是一次只发一个。
   - 只读调用（grep / glob / read / web 检索等）彼此无依赖时，放同一批发出：一次往返就能拿回全部结果，省掉多轮推理排队。
   - shell 命令（pwsh / bash）按批执行时是逐条串行的，每条都有独立的启动开销；**能用一条命令表达的多个操作，不要拆成多次 shell 调用**，合并成一段脚本一次跑完（脚本内部可自行控制顺序与并行）。
   - 批处理的收益是省往返，不等于并行加速：执行器可能把批内调用逐个串行执行，不要指望「发了 4 个调用就 4 倍加速」，更不要为了凑批而发出不需要的调用。
   - 串行留白（必须分多次调用，或等前一批结果返回再继续）：
     · 后续调用的路径、参数或内容取决于前一个调用的结果；
     · 同一文件的写操作（edit / write 同一路径）——并发写会丢失更新；
     · 大范围或破坏性的 shell 操作——必须先看目标集再执行。
4. 错误可回传：任何执行失败都要把原始错误信息（消息/调用栈/退出码）原样带回，用于判断与续跑。

探测流程（当你不确定执行器的环境语义时）：
1. 用最小探针依次尝试候选写法（如不同的模块加载方式、API 调用方式），记录哪种写法通过；
2. 以通过验证的写法为准执行后续步骤；
3. 若所有候选写法都失败，立即停止并把探针错误原样回传，不要盲目重试或猜测。`;
