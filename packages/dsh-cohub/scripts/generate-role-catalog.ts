/**
 * 构建辅助脚本：生成「角色目录」静态数据（内置提示词 + 绑定工具）。
 *
 * 数据来源（全部构建期可读，运行期零 IO）：
 *   1. src/skills.ts 的 COHUB_SKILLS：name / description / **brief**（不取 content 全文，控体积）；
 *   2. src/roles.ts：BUILTIN_ROLE_TIERS（角色→档位）、TIER_TO_PRESET（档位→preset）、
 *      TIER_TOOLS（派发层 deny 表）、ALL_TIERS；
 *   3. presets/<preset>/agent.cordis.yml：真实挂载的 `- id: / name: '@deepseek-ai/dsh-tool-*'`
 *      行 + config 开关（write / edit / fetch）+ `disabled: !!js ...` 平台门控。
 *
 * 产物（两份，内容同源）：
 *   · src/client/role-catalog.data.js —— 纯 ESM（无 import / 无 Node API），供浏览器直接 import；
 *   · src/client/index.js 里 `// BEGIN/END ROLE_CATALOG` 标记块之间 —— 占位块原地替换，
 *     因为 scripts/build-client.js 是**逐字复制** index.js，不能在构建期做打包/注入。
 *
 * 幂等：generatedAt 只在结构真的变化时才更新；结构不变则整份文件不重写（build 不抖动）。
 *
 * 用法：bun run scripts/generate-role-catalog.ts
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { COHUB_SKILLS } from "../src/skills.ts";
import { ALL_TIERS, BUILTIN_ROLE_TIERS, SHELL_TOOL, TIER_TOOLS, TIER_TO_PRESET } from "../src/roles.ts";
import type { Tier } from "../src/roles.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PRESETS_DIR = path.join(ROOT, "presets");
const DATA_OUT = path.join(ROOT, "src", "client", "role-catalog.data.js");
const CLIENT_IN = path.join(ROOT, "src", "client", "index.js");

const BEGIN_MARK = "// BEGIN ROLE_CATALOG (generated by scripts/generate-role-catalog.ts)";
const END_MARK = "// END ROLE_CATALOG";
const STAMP_SENTINEL = "__GENERATED_AT_SENTINEL__";

/** 工具中文名映射表；未知插件回落插件短名（见 {@link labelFor}） */
const LABEL_BY_PLUGIN: Readonly<Record<string, string>> = {
  "dsh-tool-fs": "文件读写",
  "dsh-tool-fs-search": "文件搜索",
  "dsh-tool-web": "联网抓取",
  "dsh-tool-bash": "Shell",
  "dsh-tool-pwsh": "Shell",
  "dsh-tool-skill": "技能",
  "dsh-tool-todo": "待办",
  "dsh-tool-jobs": "后台任务",
  "dsh-tool-goal": "目标",
  "dsh-tool-ask-user": "追问用户",
  "dsh-tool-delegation": "委派",
  "mcp-github": "GitHub",
};

/** 映射表顺序即展示优先序；未知插件排在已知之后、保持 yml 出现顺序 */
const LABEL_ORDER: readonly string[] = Object.keys(LABEL_BY_PLUGIN);

/** 参与 note 的 config 开关白名单（其余开关如 sampleOverCapGlobResults 不进 note，避免噪音） */
const SWITCH_KEYS: readonly string[] = ["write", "edit", "read", "readImage", "fetch"];

/** 一个工具项 */
interface ToolItem {
  plugin: string;
  label: string;
  note: string;
}

/** 一个档位 */
interface TierEntry {
  preset: string;
  tools: ToolItem[];
  /** 派发层 deny 表（平台相关的 shell 工具名归一化成 "shell"，保证生成物跨平台一致） */
  deny: string[];
}

/** 角色目录整体 */
interface RoleCatalog {
  generatedAt: string;
  tiers: Record<string, TierEntry>;
  roles: Record<string, { tier: Tier | null; description: string; brief: string }>;
}

/** 去掉 `@deepseek-ai/` 前缀，得到插件短名（dsh-tool-fs / mcp-github …） */
function shortName(raw: string): string {
  return raw.trim().replace(/^@deepseek-ai\//, "");
}

/** 是否是会注册模型可见工具的插件行（persona / compaction / skill-filesystem 等不算） */
function isToolPlugin(plugin: string): boolean {
  return plugin.startsWith("dsh-tool-") || plugin.startsWith("mcp-") || plugin === "dsh-cohub/co-cordis-plugin";
}

/** 插件 → 中文名；未知回落短名 */
function labelFor(plugin: string): string {
  return LABEL_BY_PLUGIN[plugin] ?? plugin;
}

/** disabled: !!js 表达式 → 中文门控文案 */
function gateText(expr: string): string {
  const code = expr.trim();
  if (/process\.platform\s*!==\s*['"]win32['"]/.test(code)) return "仅 Windows";
  if (/process\.platform\s*===\s*['"]win32['"]/.test(code)) return "仅非 Windows";
  return "平台门控";
}

/**
 * 解析一个 preset 的 agent.cordis.yml。
 *
 * 只做「顶层 `- id:` 分段 + 段内 name/disabled/config 拾取」，不是通用 YAML 解析器：
 * preset 里需要的信息只有这三类，为 300 行写 YAML 依赖不值得。
 */
function parsePreset(presetFile: string): ToolItem[] {
  if (!fs.existsSync(presetFile)) {
    throw new Error(`❌ 缺少 preset 文件：${presetFile}`);
  }
  const lines = fs.readFileSync(presetFile, "utf-8").split(/\r?\n/);

  // 顶层分段：`- id:` 缩进为 0 的行开始新段
  const sections: string[][] = [];
  let current: string[] | null = null;
  for (const line of lines) {
    if (/^- id:\s*\S+/.test(line)) {
      current = [line];
      sections.push(current);
    } else if (current !== null) {
      current.push(line);
    }
  }

  const tools: ToolItem[] = [];
  const seen = new Set<string>();

  for (const section of sections) {
    const names: string[] = [];
    const gates: string[] = [];
    const switches: Record<string, string> = {};

    for (const line of section) {
      const nameMatch = /^\s+name:\s*'([^']+)'\s*$/.exec(line) ?? /^\s+name:\s*([^\s'#]+)\s*$/.exec(line);
      if (nameMatch !== null) {
        const plugin = shortName(nameMatch[1]!);
        if (isToolPlugin(plugin) && !names.includes(plugin)) names.push(plugin);
        continue;
      }
      const gateMatch = /^\s+disabled:\s*!!js\s+(.+)$/.exec(line);
      if (gateMatch !== null) {
        gates.push(gateText(gateMatch[1]!));
        continue;
      }
      const switchMatch = /^\s+([A-Za-z][A-Za-z0-9]*):\s*(true|false)\s*$/.exec(line);
      if (switchMatch !== null && SWITCH_KEYS.includes(switchMatch[1]!)) {
        switches[switchMatch[1]!] = switchMatch[2]!;
      }
    }

    // 段内恰好一个工具时，段内的开关 / 门控归属它；多工具（group 段）不猜归属
    const owner = names.length === 1 ? names[0]! : null;
    for (const plugin of names) {
      if (seen.has(plugin)) continue;
      seen.add(plugin);
      tools.push({
        plugin,
        label: labelFor(plugin),
        note: owner === null ? "" : noteFor(plugin, switches, gates),
      });
    }
  }

  // 排序：映射表顺序优先，未知插件按 yml 出现顺序排在后面
  const rank = (tool: ToolItem): number => {
    const at = LABEL_ORDER.indexOf(tool.plugin);
    return at >= 0 ? at : LABEL_ORDER.length + tools.findIndex((t) => t.plugin === tool.plugin);
  };
  return tools.sort((a, b) => rank(a) - rank(b));
}

/** 由 config 开关 + 平台门控拼出 note（空串表示无特别开关） */
function noteFor(plugin: string, switches: Record<string, string>, gates: readonly string[]): string {
  const bits: string[] = [];
  const isFs = plugin === "dsh-tool-fs";
  const isWeb = plugin === "dsh-tool-web";

  if (isFs) {
    if (switches.write === "false" && switches.edit === "false") bits.push("只读");
    else if (switches.write === "true" || switches.edit === "true") bits.push("可写");
  }
  if (isWeb) {
    if (switches.fetch === "false") bits.push("不联网");
    else if (switches.fetch === "true") bits.push("可联网");
  }
  for (const key of SWITCH_KEYS) {
    const value = switches[key];
    if (value === undefined) continue;
    if (isFs && (key === "write" || key === "edit")) continue;
    if (isWeb && key === "fetch") continue;
    bits.push(`${key}: ${value}`);
  }
  for (const gate of gates) {
    if (!bits.includes(gate)) bits.push(gate);
  }
  return bits.join("、");
}

/** 构造完整目录数据 */
function buildCatalog(generatedAt: string): RoleCatalog {
  const tiers: Record<string, TierEntry> = {};
  for (const tier of ALL_TIERS) {
    const preset = TIER_TO_PRESET[tier];
    const deny = TIER_TOOLS[tier].deny.map((name) => (name === SHELL_TOOL || name === "bash" || name === "pwsh" ? "shell" : name));
    tiers[tier] = {
      preset,
      tools: parsePreset(path.join(PRESETS_DIR, preset, "agent.cordis.yml")),
      deny,
    };
  }

  const roles: RoleCatalog["roles"] = {};
  for (const skill of COHUB_SKILLS) {
    roles[skill.name] = {
      tier: BUILTIN_ROLE_TIERS[skill.name] ?? null,
      description: skill.description,
      brief: skill.brief,
    };
  }

  return { generatedAt, tiers, roles };
}

const HEADER_DATA = [
  "// 自动生成，请勿手动编辑。源：scripts/generate-role-catalog.ts",
  "// 数据来源：src/skills.ts（name/description/brief）、src/roles.ts（档位映射与 deny 表）、",
  "//          presets/<preset>/agent.cordis.yml（真实挂载的插件行 + config 开关 + 平台门控）",
  "// 浏览器消费：纯 ESM，无 import、无 Node API。",
].join("\n");

function renderDataFile(catalog: RoleCatalog): string {
  return `${HEADER_DATA}\nexport const ROLE_CATALOG = ${JSON.stringify(catalog, null, 2)};\n`;
}

/** index.js 内联块（factory 体内，缩进 4；JSON 续行再多 4） */
function renderInlineBlock(catalog: RoleCatalog): string {
  const body = JSON.stringify(catalog, null, 2)
    .split("\n")
    .map((line, index) => (index === 0 ? line : `    ${line}`))
    .join("\n");
  return `    const ROLE_CATALOG = ${body};`;
}

/** 已存在产物里的 generatedAt（用于幂等：结构未变时保留旧时间戳） */
function readExistingStamp(file: string): string | null {
  if (!fs.existsSync(file)) return null;
  const match = /"generatedAt":\s*"([^"]*)"/.exec(fs.readFileSync(file, "utf-8"));
  return match === null ? null : match[1]!;
}

/** 把文本里的 generatedAt 值抹成哨兵，用于「结构是否变化」的比较 */
function normalizeStamp(text: string): string {
  return text.replace(/"generatedAt":\s*"[^"]*"/, `"generatedAt": "${STAMP_SENTINEL}"`);
}

function writeDataFile(catalog: RoleCatalog): { text: string; bytes: number; changed: boolean } {
  const text = renderDataFile(catalog);
  const previous = fs.existsSync(DATA_OUT) ? fs.readFileSync(DATA_OUT, "utf-8") : null;
  if (previous === text) return { text, bytes: Buffer.byteLength(text, "utf-8"), changed: false };
  fs.writeFileSync(DATA_OUT, text, "utf-8");
  return { text, bytes: Buffer.byteLength(text, "utf-8"), changed: true };
}

/** 原地替换 index.js 的两个标记之间的内容 */
function writeInlineBlock(catalog: RoleCatalog): boolean {
  const source = fs.readFileSync(CLIENT_IN, "utf-8");
  const beginAt = source.indexOf(BEGIN_MARK);
  const endAt = source.indexOf(END_MARK);
  if (beginAt < 0 || endAt < 0 || endAt < beginAt) {
    console.warn(`⚠️ ${CLIENT_IN} 缺少 BEGIN/END ROLE_CATALOG 标记块，跳过内联`);
    return false;
  }
  const block = renderInlineBlock(catalog);
  const next = source.slice(0, beginAt + BEGIN_MARK.length) + "\n" + block + "\n    " + source.slice(endAt);
  if (next === source) return false;
  fs.writeFileSync(CLIENT_IN, next, "utf-8");
  return true;
}

// ── 主流程 ─────────────────────────────────────────────────────────────────

function main(): void {
  const previousStamp = readExistingStamp(DATA_OUT);
  const probe = renderDataFile(buildCatalog(STAMP_SENTINEL));
  const stable = previousStamp !== null && normalizeStamp(
    fs.existsSync(DATA_OUT) ? fs.readFileSync(DATA_OUT, "utf-8") : "",
  ) === normalizeStamp(probe);
  const stamp = stable ? previousStamp : new Date().toISOString();
  const catalog = buildCatalog(stamp);

  // ── 自验（数据形状不成立就让构建失败，不产出坏目录）──────────────────────
  const roleNames = Object.keys(catalog.roles);
  const tierNames = Object.keys(catalog.tiers);
  if (roleNames.length !== COHUB_SKILLS.length || roleNames.length < 16) {
    throw new Error(`❌ 角色数不符：${roleNames.length}（COHUB_SKILLS ${COHUB_SKILLS.length}）`);
  }
  if (tierNames.length !== 5) throw new Error(`❌ 档位数不符：${tierNames.length}（应为 5）`);
  for (const [tier, entry] of Object.entries(catalog.tiers)) {
    if (entry.preset.length === 0) throw new Error(`❌ 档位 ${tier} 缺 preset`);
    if (entry.tools.length < 3) throw new Error(`❌ 档位 ${tier} 工具项不足 3（当前 ${entry.tools.length}）`);
  }
  const readonlyTools = catalog.tiers["ro"]!.tools;
  if (readonlyTools.some((tool) => tool.label === "Shell")) throw new Error("❌ ro 档不应含 Shell");
  if (!readonlyTools.some((tool) => tool.note.includes("只读"))) throw new Error("❌ ro 档缺少「只读」标注");
  const writeTools = catalog.tiers["rw"]!.tools;
  if (!writeTools.some((tool) => tool.label === "Shell")) throw new Error("❌ rw 档应含 Shell");

  const data = writeDataFile(catalog);
  const longContent = COHUB_SKILLS[0]!.content.slice(0, 200);
  if (data.text.includes(longContent)) throw new Error("❌ 生成物混入了 skills 全文 content");
  if (data.bytes > 60000) throw new Error(`❌ 生成物体积异常：${data.bytes} 字节`);

  const inlineChanged = writeInlineBlock(catalog);

  console.log(
    `✅ 已生成角色目录：${roleNames.length} 角色 / ${tierNames.length} 档位 → ` +
      `src/client/role-catalog.data.js（${data.bytes} 字节${data.changed ? "" : "，未变化"}）` +
      `${inlineChanged ? "，index.js 内联块已更新" : "，index.js 内联块未变化"}`,
  );
}

main();
